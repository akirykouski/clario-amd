"""Render eval/RESULTS.md from eval/results/*.json. Nothing is typed by hand: every number comes from a result file.

    python eval/make_results_md.py

A result file must carry n, dataset, model, backend, date. Files that miss a field are listed under
"Rejected files" and their numbers are not shown. Dry-run and offline files are listed apart from model runs.
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REQUIRED = ("n", "dataset", "model", "backend", "date")


def f3(v):
    return "n/a" if v is None else f"{v:.3f}"


def load(results_dir):
    ok, bad = [], []
    for p in sorted(glob.glob(os.path.join(results_dir, "*.json"))):
        try:
            r = json.load(open(p))
        except Exception as e:
            bad.append((os.path.basename(p), f"unreadable: {e}")); continue
        miss = [k for k in REQUIRED if k not in r]
        (bad.append((os.path.basename(p), "missing " + ", ".join(miss))) if miss else ok.append((os.path.basename(p), r)))
    return ok, bad


def render(results_dir):
    ok, bad = load(results_dir)
    ext = [(n, r) for n, r in ok if n.startswith("extraction_")]
    runs = [(n, r) for n, r in ext if not r.get("dry_run")]
    dry = [(n, r) for n, r in ext if r.get("dry_run")]
    curves = [(n, r) for n, r in ok if n.startswith("review_curve_")]
    conf = [(n, r) for n, r in ok if n.startswith("conformal_") and not r.get("dry_run")]
    conf_dry = [(n, r) for n, r in ok if n.startswith("conformal_") and r.get("dry_run")]
    other = [(n, r) for n, r in ok if (n, r) not in ext and (n, r) not in curves and not n.startswith("conformal_")]
    L = ["# Results", "", "Generated by `eval/make_results_md.py` from `eval/results/*.json`. Do not edit by hand. "
         "Every number below is read from the file named in its row.", ""]
    L += ["## Extraction (model runs)", ""]
    if runs:
        L += ["| file | model | backend | dataset | n | date | entity F1 | HPO-ID acc | negation acc | family acc | grounding | JSON valid | ECE | p50 / p95 s |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for n, r in runs:
            lat = f"{r['latency_p50_s']:.2f} / {r['latency_p95_s']:.2f}" if "latency_p50_s" in r else "n/a"
            L.append(f"| {n} | {r['model']} | {r['backend']} | {r['dataset']} | {r['n']} | {r['date']} | {f3(r.get('entity_f1'))} | "
                     f"{f3(r.get('hpo_id_accuracy'))} | {f3(r.get('negation_accuracy'))} | {f3(r.get('family_history_accuracy'))} | "
                     f"{f3(r.get('quote_grounding_rate'))} | {f3(r.get('json_validity_rate'))} | {f3(r.get('ece'))} | {lat} |")
        partial = [n for n, r in runs if r.get("gold_complete") is False]
        if partial:
            L += ["", "Partial gold (unlabelled mentions exist, precision and F1 are lower bounds): " + ", ".join(partial) + "."]
    else:
        L.append("No model run recorded yet.")
    L += ["", "## Review curve (share of entities routed to review)", ""]
    if curves:
        L += ["| file | model | dataset | n | date | 1% error | 2% error | 5% error | items 1% / 2% / 5% |", "|---|---|---|---|---|---|---|---|---|"]
        for n, r in curves:
            t = r.get("tolerances", {})
            ent = [f3(t.get(k, {}).get("entity", {}).get("review_share")) for k in ("1pct", "2pct", "5pct")]
            itm = " / ".join(f3(t.get(k, {}).get("item", {}).get("review_share")) for k in ("1pct", "2pct", "5pct"))
            L.append(f"| {n} | {r['model']} | {r['dataset']} | {r['n']} | {r['date']} | {ent[0]} | {ent[1]} | {ent[2]} | {itm} |")
        L += ["", "Share routed to review so that the auto-accepted rest stays within the tolerated error. It is a routing share, not coverage or accuracy, and it rests on the confidence named in confidence_source of each file (self-consistency, the app's signal, or the model's own number). Misses carry no confidence and are not routed."]
    else:
        L.append("No review curve recorded yet (needs a run with `--sc-n N`, or `--confidence` for the model's own number, then `eval/review_curve.py`).")
    L += ["", "## Review threshold with a guarantee (conformal)", ""]
    if conf:
        L += ["| file | model | dataset | n | date | alpha | delta | threshold | auto-accept (held out) | error (held out) |", "|---|---|---|---|---|---|---|---|---|---|"]
        for n, r in conf:
            L.append(f"| {n} | {r['model']} | {r['dataset']} | {r['n']} | {r['date']} | {f3(r.get('alpha'))} | {f3(r.get('delta'))} | "
                     f"{f3(r.get('threshold'))} | {f3(r.get('auto_accept_rate'))} | {f3(r.get('heldout_error'))} |")
        L += ["", "With probability at least 1 - delta, entities at or above the threshold have an error rate of at most alpha, for data like the calibration set (split calibration, Learn-then-Test). The held-out numbers are one draw on the other half, shown for transparency."]
    else:
        L.append("No certified threshold recorded yet (`eval/conformal.py` on a `--sc-n` run).")
    if other:
        L += ["", "## Other results", "", "| file | model | backend | dataset | n | date |", "|---|---|---|---|---|---|"]
        L += [f"| {n} | {r['model']} | {r['backend']} | {r['dataset']} | {r['n']} | {r['date']} |" for n, r in other]
    L += ["", "## Offline checks (not model results)", ""]
    if dry:
        L += ["| file | dataset | n | date | entity F1 | note |", "|---|---|---|---|---|---|"]
        L += [f"| {n} | {r['dataset']} | {r['n']} | {r['date']} | {f3(r.get('entity_f1'))} | {r.get('note', 'dry run, no model')} |" for n, r in dry]
        L += [f"| {n} | {r['dataset']} | {r['n']} | {r['date']} | n/a | {r.get('note', 'dry run, no model')} |" for n, r in conf_dry]
    elif conf_dry:
        L += ["| file | dataset | n | date | entity F1 | note |", "|---|---|---|---|---|---|"]
        L += [f"| {n} | {r['dataset']} | {r['n']} | {r['date']} | n/a | {r.get('note', 'dry run, no model')} |" for n, r in conf_dry]
    else:
        L.append("None.")
    if bad:
        L += ["", "## Rejected files", ""] + [f"- `{n}`: {why}" for n, why in bad]
    return "\n".join(L) + "\n"


def main():
    text = render(os.path.join(HERE, "results"))
    open(os.path.join(HERE, "RESULTS.md"), "w").write(text)
    print(text)


if __name__ == "__main__":
    main()
