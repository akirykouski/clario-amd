import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "eval" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


rc = load("review_curve")
md = load("make_results_md")


def test_risk_coverage_ties_and_order():
    pts = [(0.9, 1), (0.9, 0), (0.5, 1)]
    curve = rc.risk_coverage(pts)
    assert curve[0] == (0.9, 2 / 3, 0.5) and abs(curve[1][1] - 1.0) < 1e-9 and abs(curve[1][2] - 1 / 3) < 1e-9
    assert rc.risk_coverage([]) == []


def test_review_share_picks_largest_coverage_within_tolerance():
    # 90 confident and right, 10 unsure and half wrong
    pts = [(0.95, 1)] * 90 + [(0.4, 1)] * 5 + [(0.4, 0)] * 5
    r5 = rc.review_share(pts, 0.05)
    assert r5["threshold"] == 0.4 and abs(r5["coverage"] - 1.0) < 1e-9
    r1 = rc.review_share(pts, 0.01)
    assert r1["threshold"] == 0.95 and abs(r1["review_share"] - 0.10) < 1e-9 and r1["error_at_threshold"] == 0.0
    # at 5% the whole set has 5% error exactly -> everything auto-accepted
    assert abs(r5["review_share"]) < 1e-9
    # nothing qualifies when even the most confident group is too wrong
    none = rc.review_share([(0.9, 0), (0.9, 0)], 0.05)
    assert none["threshold"] is None and none["review_share"] == 1.0


def test_item_level_uses_lowest_entity_confidence():
    items = [{"entities": [{"confidence": 0.9, "correct": 1}, {"confidence": 0.3, "correct": 0}]},
             {"entities": [{"confidence": 0.8, "correct": 1}]}, {"entities": []}]
    assert sorted(rc.item_points(items)) == [(0.3, 0), (0.8, 1)]
    assert len(rc.entity_points(items)) == 3


def result(label, **kw):
    r = {"label": label, "dataset": "v3/test", "model": "m", "backend": "vllm", "date": "2026-10-15", "n": 4,
         "entity_f1": 0.5, "hpo_id_accuracy": 0.4, "negation_accuracy": None, "family_history_accuracy": 0.9,
         "quote_grounding_rate": 1.0, "json_validity_rate": 1.0, "ece": 0.05, "latency_p50_s": 1.0, "latency_p95_s": 2.0,
         "fn": 1, "dry_run": False}
    r.update(kw)
    return r


def test_review_curve_file_and_results_markdown(tmp_path):
    per_item = [{"id": str(i), "n_gold": 1, "n_pred": 1, "entities": [{"confidence": 0.9 if i < 8 else 0.2, "correct": 1 if i < 8 else 0}]}
                for i in range(10)]
    src = tmp_path / "extraction_ft.json"
    src.write_text(json.dumps(result("ft", per_item=per_item)))
    (tmp_path / "extraction_nocal.json").write_text(json.dumps(result("nocal")))
    rc.main([str(src), str(tmp_path / "extraction_nocal.json")])
    curve = json.load(open(tmp_path / "review_curve_ft.json"))
    assert not (tmp_path / "review_curve_nocal.json").exists()
    for k in ("n", "dataset", "model", "backend", "date"):
        assert k in curve
    t = curve["tolerances"]
    assert set(t) == {"1pct", "2pct", "5pct"} and abs(t["1pct"]["entity"]["review_share"] - 0.2) < 1e-9
    assert curve["unrouted_misses"] == 1

    (tmp_path / "extraction_dryrun-gold-vs-gold.json").write_text(json.dumps(result("dryrun-gold-vs-gold", dry_run=True, entity_f1=1.0, note="no model")))
    (tmp_path / "broken.json").write_text(json.dumps({"label": "x", "entity_f1": 0.99}))
    text = md.render(str(tmp_path))
    assert "extraction_ft.json | m | vllm | v3/test | 4 | 2026-10-15 | 0.500" in text
    assert "n/a" in text  # missing negation accuracy is shown as n/a, never as a number
    assert "review_curve_ft.json" in text and "0.200" in text
    assert "Offline checks (not model results)" in text and "extraction_dryrun-gold-vs-gold.json" in text
    assert text.index("extraction_dryrun-gold-vs-gold.json") > text.index("Offline checks")  # never in the model table
    assert "broken.json" in text and "missing n, dataset, model, backend, date" in text
    assert "0.990" not in text  # a file without provenance contributes no number


